"""Karaoke captions: word-by-word fill, line pop, safe-zone placement.

The look: the whole line is readable, earlier words are already filled in the
highlight colour, the current word is mid-transition — that is the style
retention-obsessed editors charge for. It is plain ASS `\\kf`, so it costs one
ffmpeg pass and no extra dependency.
"""

from __future__ import annotations

from dataclasses import dataclass
from itertools import pairwise
from pathlib import Path

from autoshorts.config import Settings
from autoshorts.models import Segment, Word

_POWER = {"stop", "never", "nobody", "secret", "mistake", "why", "free", "fast",
          "money", "first", "last", "worst", "best", "wrong", "true", "hold",
          "arrête", "jamais", "erreur", "pourquoi", "argent"}


@dataclass
class Group:
    start: float
    end: float
    lines: list[list[Word]]
    segment: int = 0
    emphatic: bool = False

    @property
    def words(self) -> list[Word]:
        return [word for line in self.lines for word in line]


def hex_to_ass(value: str) -> str:
    """'#FFE81A' -> '&H001AE8FF&' (ASS stores BB GG RR with alpha first)."""
    raw = (value or "").strip().lstrip("#")
    if len(raw) == 3:
        raw = "".join(c * 2 for c in raw)
    if len(raw) != 6:
        raw = "FFFFFF"
    r, g, b = raw[0:2], raw[2:4], raw[4:6]
    return f"&H00{b.upper()}{g.upper()}{r.upper()}&"


def _time(seconds: float) -> str:
    seconds = max(0.0, seconds)
    h = int(seconds // 3600)
    m = int((seconds % 3600) // 60)
    return f"{h}:{m:02d}:{seconds % 60:05.2f}"


def _escape(text: str) -> str:
    return text.replace("{", "(").replace("}", ")").replace("\\", "/")


def _end_of_thought(word: Word) -> bool:
    return word.text.rstrip().endswith((".", "!", "?", ":", "—", "…"))


def group_words(
    words: list[Word],
    settings: Settings | None = None,
    max_words: int = 3,
    max_chars: int = 14,
    max_seconds: float = 2.4,
) -> list[Group]:
    """Pack the clock into 1-2 line bursts that break on thought boundaries."""
    groups: list[Group] = []
    buffer: list[Word] = []

    def chars(items: list[Word]) -> int:
        return sum(len(w.text) for w in items)

    for word in words:
        if buffer and (
            len(buffer) >= max_words
            or chars(buffer) + len(word.text) > max_chars * 2
            or word.end - buffer[0].start > max_seconds
        ):
            groups.append(_pack(buffer))
            buffer = []
        buffer.append(word)
        if _end_of_thought(word) or chars(buffer) >= max_chars:
            groups.append(_pack(buffer))
            buffer = []
    if buffer:
        groups.append(_pack(buffer))
    return [g for g in groups if g.words]


def _pack(buffer: list[Word]) -> Group:
    lines: list[list[Word]] = [[]]
    width = 0
    for word in buffer:
        if lines[-1] and width + len(word.text) + 1 > 14:
            lines.append([])
            width = 0
        lines[-1].append(word)
        width += len(word.text) + 1
    lowered = {w.text.lower().strip(".,!?;:") for w in buffer}
    return Group(
        start=round(buffer[0].start, 3),
        end=round(buffer[-1].end, 3),
        lines=[line for line in lines if line],
        emphatic=bool(lowered & _POWER) or len(buffer) <= 2,
    )


def _karaoke(group: Group, event_end: float) -> str:
    """One continuous karaoke clock over the event; `\\N` only breaks lines."""
    parts: list[str] = []
    break_after = [sum(len(line) for line in group.lines[:i + 1]) - 1
                   for i in range(len(group.lines) - 1)]
    words = group.words
    for position, word in enumerate(words):
        if position:
            parts.append(r"\N" if position - 1 in break_after else " ")
        duration = word.end - word.start
        if position == len(words) - 1:
            duration = max(duration, event_end - word.start)
        parts.append(f"{{\\kf{max(4, round(duration * 100))}}}{_escape(word.text)}")
    return "".join(parts)


def build_ass(groups: list[Group], settings: Settings) -> str:
    width, height = settings.width, settings.height
    size = max(52, int(width * 0.104))
    margin_v = int(height * 0.235)
    font = settings.caption_font or "Arial Black"
    highlight = hex_to_ass(settings.caption_highlight)
    base = hex_to_ass(settings.caption_base)

    header = f"""[Script Info]
; Generated by AutoShorts
ScriptType: v4.00+
PlayResX: {width}
PlayResY: {height}
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeThrough, AtCursor, SafePaste, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Caption,{font},{size},{highlight},{base},&H00000000,&H80000000,-1,0,0,0,0,0,1.0,0,1,7,3,2,48,48,{margin_v},1
Style: CaptionBig,{font},{int(size * 1.16)},{highlight},{base},&H00000000,&H80000000,-1,0,0,0,0,0,1.0,0,1,8,4,2,48,48,{margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    events: list[str] = []
    for group in groups:
        if group.end - group.start < 0.05:
            continue
        # Override tags must sit inside one {...} block; a bare `\fad` makes
        # libass refuse the whole file.
        effects = r"\fad(70,45)"
        if group.emphatic:
            effects += r"\fscx100\fscy100\t(0,70,\fscx112\fscy112)\t(70,190,\fscx100\fscy100)"
        style = "CaptionBig" if group.segment == 0 else "Caption"
        events.append(
            f"Dialogue: 0,{_time(group.start)},{_time(group.end + 0.04)},{style},,0,0,0,,"
            f"{{{effects}}}{_karaoke(group, group.end + 0.04)}"
        )
    return header + "\n".join(events) + "\n"


def write_ass(groups: list[Group], settings: Settings, out: Path) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_ass(groups, settings), encoding="utf-8")
    return out


def flatten(segments: list[Segment], settings: Settings) -> list[Group]:
    """One caption timeline across the whole video, with no overlaps."""
    groups: list[Group] = []
    for segment in segments:
        for group in group_words(segment.words, settings):
            group.segment = segment.index
            groups.append(group)
    for previous, current in pairwise(groups):
        if current.start <= previous.end:
            previous.end = round(current.start - 0.01, 3)
    return [g for g in groups if g.end > g.start and g.words]


def write_srt(groups: list[Group], out: Path) -> Path:
    """Plain-text fallback for ffmpeg builds without libass (handy to edit too)."""

    def stamp(seconds: float) -> str:
        ms = int(round(max(0.0, seconds) * 1000))
        return (f"{ms // 3600000:02d}:{ms % 3600000 // 60000:02d}:"
                f"{ms % 60000 // 1000:02d},{ms % 1000:03d}")

    blocks = []
    for index, group in enumerate(groups, start=1):
        body = "\n".join(" ".join(w.text for w in line) for line in group.lines)
        blocks.append(f"{index}\n{stamp(group.start)} --> {stamp(group.end)}\n{body}\n")
    out.write_text("\n".join(blocks), encoding="utf-8")
    return out
